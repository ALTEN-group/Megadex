import { existsSync, readFileSync } from "node:fs";
import { resolve } from "node:path";

export type E2eCredentials = {
  email: string;
  password: string;
};

function findCredentials(
  node: unknown,
  targetEmail?: string,
): E2eCredentials | undefined {
  if (!node || typeof node !== "object") {
    return undefined;
  }

  if (Array.isArray(node)) {
    for (const item of node) {
      const found = findCredentials(item, targetEmail);
      if (found) return found;
    }
    return undefined;
  }

  const record = node as Record<string, unknown>;
  if (
    typeof record.email === "string" &&
    !record.email.startsWith("__") &&
    typeof record.pwd === "string" &&
    !record.pwd.startsWith("__") &&
    record.pwd !== "WrongPassword123!" &&
    (!targetEmail || record.email === targetEmail)
  ) {
    return { email: record.email, password: record.pwd };
  }

  for (const value of Object.values(record)) {
    const found = findCredentials(value, targetEmail);
    if (found) return found;
  }

  return undefined;
}

const openapiPath = resolve(
  __dirname,
  "../../../swagger/src/megadex.openapi.json",
);

function readOpenapiCredentials(
  targetEmail?: string,
): E2eCredentials | undefined {
  if (!existsSync(openapiPath)) return undefined;
  try {
    const openapi = JSON.parse(readFileSync(openapiPath, "utf8")) as unknown;
    return findCredentials(openapi, targetEmail);
  } catch {
    return undefined;
  }
}

/**
 * Resolves login credentials for e2e.
 * Prefer E2E_EMAIL / E2E_PASSWORD; otherwise read the password generated by
 * `./scripts/setup-mocks.sh` from swagger/src/megadex.openapi.json.
 */
export const hasAdminCredentials = (): boolean =>
  Boolean(
    process.env.E2E_PASSWORD || readOpenapiCredentials(process.env.E2E_EMAIL),
  );

export function getAdminCredentials(
  email = process.env.E2E_EMAIL,
): E2eCredentials {
  if (process.env.E2E_PASSWORD) {
    return {
      email: email ?? "admin@example.com",
      password: process.env.E2E_PASSWORD,
    };
  }

  const found = readOpenapiCredentials(email) ?? readOpenapiCredentials();
  if (!found) {
    throw new Error(
      `No password found for ${email ?? "seeded dev user"}. Set E2E_PASSWORD or run ./scripts/setup-mocks.sh.`,
    );
  }

  return found;
}
