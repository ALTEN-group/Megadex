CREATE OR REPLACE VIEW users AS
  SELECT
    u.id,
    u.gender,
    u.civility,
    u."firstName",
    u."middleName",
    u."lastName",
    u.nickname,
    u.email,
    u."backupEmail",
    u.address,
    u."zipCode",
    u.city,
    u.country,
    u.nationality,
    u.phone,
    u.birthdate,
    u.portrait,
    u.language,
    u.job,
    u.company,
    u.website,
    u.facebook,
    u.instagram,
    u.x,
    u."linkedIn",
    u."youTube",
    u."tikTok",
    u."gitHub",
    u.pinterest,
    u.discord,
    u.reddit,
    u.twitch,
    u."gdprConsentedAt",
    u."marketingConsentedAt",
    u.active,
    u.archived,
    u."archivedAt",
    u."createdAt",
    u."creatorId",
    u."creatorName",
    u."updatedAt",
    u."updaterId",
    u."updaterName",
    array_agg(ur."roleId" ORDER BY ur."roleId") FILTER (WHERE ur."roleId" IS NOT NULL) AS "rolesArrayAgg"
  FROM "user" AS u
  LEFT JOIN user_role AS ur ON ur."userId" = u.id
  GROUP BY u.id
  ORDER BY u.id ASC
;
